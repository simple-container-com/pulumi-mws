// Package mws is the Pulumi bridge over MWS Cloud Platform's official
// Terraform provider (mws-cloud-platform/terraform-provider-mws, Apache-2.0).
//
// It is a STATIC bridge, generated once per upstream version and published from
// this repo, in the same shape as its siblings simple-container-com/pulumi-yandex
// and simple-container-com/pulumi-sbercloud. The alternative considered and
// rejected was Pulumi's PARAMETERIZED bridge (`pulumi package add
// terraform-provider ./terraform-provider-mws`), which SC proved out for
// Cloud.ru Evolution on 2026-10-22. Two measurements killed it for MWS:
//
//   - Both provider registries are geoblocked from RU networks. Measured
//     2026-11-05: registry.terraform.io answers "Content not available in your
//     region" and registry.opentofu.org answers 403. The parameterized bridge
//     resolves its upstream from a registry by default, and `get.pulumi.com`
//     (where the `terraform-provider` bridge plugin itself lives) is on the same
//     block list. A static bridge moves that whole dependency to build time, on
//     a runner we control.
//
//   - MWS models resources Kubernetes-style — `kind` / `metadata` / `spec` /
//     `ref` / `usages`, nested four to five levels deep. tfgen counts 1496
//     inputs across 41 resources. The parameterized bridge's untyped
//     RegisterPackageResource turns a misspelled nested field into a
//     deploy-time error; the generated SDK turns it into a compile error. For
//     a provider this deeply nested that difference is the whole ballgame.
package mws

import (
	// Allow embedding bridge-metadata.json in the provider.
	_ "embed"

	mwsprovider "go.mws.cloud/terraform-provider-mws/service/provider"

	pfbridge "github.com/pulumi/pulumi-terraform-bridge/v3/pkg/pf/tfbridge"
	"github.com/pulumi/pulumi-terraform-bridge/v3/pkg/tfbridge"
	"github.com/pulumi/pulumi-terraform-bridge/v3/pkg/tfbridge/tokens"

	"github.com/simple-container-com/pulumi-mws/provider/pkg/version"
)

// mainMod is the fallback module for any upstream resource whose name does not
// start with one of the service prefixes in knownModules below. Keeping a
// non-erroring default means a new upstream service lands in `mws:index/...`
// rather than failing the build — but see the comment on knownModules: that is
// a signal to add the module, not a resting place.
const mainMod = "index"

// knownModules are the service prefixes upstream uses in its Terraform resource
// names (`mws_compute_virtual_machine` → module `compute`, resource
// `VirtualMachine`). They are derived from the upstream `service/resources/*`
// and `service/datasources/*` package layout, which is itself generated by
// MWS's own `mwsapigen`.
//
// WHY THIS LIST IS NOT `tokens.SingleModule`: a token's string value is a
// FROZEN PUBLIC CONTRACT once published — every SC plugin, stack state file and
// URN that references a resource embeds it. SingleModule would have produced
// `mws:index/computeVirtualMachine:ComputeVirtualMachine`, stuttering the
// service name into the type and flattening fifteen services into one module.
// Getting this wrong is cheap to fix today and impossible to fix after the
// first release.
//
// Adding an upstream service: add its prefix here and regenerate. Resources
// silently landing in `mws:index/...` mean a prefix is missing.
var knownModules = []string{
	"certmanager",
	"compute",
	"gpt",
	"iam",
	"kms",
	"mclickhouse",
	"metastore",
	"mk8s",
	"mkafka",
	"mpostgres",
	"nlb",
	"queue",
	"resmanager",
	"secretmanager",
	"vpc",
}

//go:embed cmd/pulumi-resource-mws/bridge-metadata.json
var metadata []byte

// Provider returns the bridged provider info for MWS Cloud Platform.
func Provider() tfbridge.ProviderInfo {
	// ShimProvider, not ShimProviderWithContext: upstream's NewProvider takes no
	// context and builds no clients until Configure, so there is nothing for a
	// context to cancel at construction time.
	//
	// NewProvider returns a FACTORY (func() provider.Provider) because that is
	// what providerserver.Serve wants; ShimProvider wants the instance, hence the
	// trailing call.
	prov := tfbridge.ProviderInfo{
		P:    pfbridge.ShimProvider(mwsprovider.NewProvider(version.Version)()),
		Name: "mws",
		// Version is load-bearing beyond cosmetics: pf/tfbridge.Main refuses to
		// serve when it is empty or not semver-compatible.
		Version:     version.Version,
		DisplayName: "MWS Cloud Platform",
		Publisher:   "Simple Container",
		License:     "Apache-2.0",
		Description: "A Pulumi package for creating and managing MWS Cloud Platform resources.",
		Keywords:    []string{"pulumi", "mws", "mts", "category/cloud"},
		Homepage:    "https://github.com/simple-container-com/pulumi-mws",
		Repository:  "https://github.com/simple-container-com/pulumi-mws",
		// PluginDownloadURL is how the Pulumi engine finds the resource plugin at
		// deploy time. Because this repo is not under the `pulumi` GitHub org the
		// engine cannot guess it, and without this the engine looks for
		// `pulumi-resource-mws` on get.pulumi.com and 404s. The `github://` scheme
		// resolves to
		//   api.github.com/repos/<org>/pulumi-mws/releases/tags/v<version>
		// and expects an asset named pulumi-resource-mws-v<version>-<os>-<arch>.tar.gz;
		// .github/workflows/release.yml is the other half of that contract.
		PluginDownloadURL: "github://api.github.com/simple-container-com/pulumi-mws",
		// GitHubOrg points at UPSTREAM, not at us — the bridge uses it to locate
		// the provider's docs for description scraping.
		GitHubOrg:    "mws-cloud-platform",
		MetadataInfo: tfbridge.NewProviderMetadata(metadata),

		// Every provider-level config key doubles as an env var, matching the
		// names upstream's own provider documents. SC's plugin passes credentials
		// explicitly rather than relying on ambient env, but keeping the env
		// defaults means a human can drive the generated SDK the same way they
		// drive `terraform`.
		Config: map[string]*tfbridge.SchemaInfo{
			"endpoint": {
				Default: &tfbridge.DefaultInfo{EnvVars: []string{"MWS_BASE_ENDPOINT"}},
			},
			"mws_token": {
				Default: &tfbridge.DefaultInfo{EnvVars: []string{"MWS_TOKEN"}},
			},
			"service_account_authorized_key_path": {
				Default: &tfbridge.DefaultInfo{EnvVars: []string{"MWS_SERVICE_ACCOUNT_AUTHORIZED_KEY_PATH"}},
			},
			"project": {
				Default: &tfbridge.DefaultInfo{EnvVars: []string{"MWS_PROJECT"}},
			},
			"zone": {
				Default: &tfbridge.DefaultInfo{EnvVars: []string{"MWS_ZONE"}},
			},
		},

		Golang: &tfbridge.GolangInfo{
			ImportBasePath:                 "github.com/simple-container-com/pulumi-mws/sdk/go/mws",
			GenerateResourceContainerTypes: true,
			GenerateExtraInputTypes:        true,
			// RespectSchemaVersion makes the generated SDK link against the
			// provider version in the schema rather than a floating one.
			RespectSchemaVersion: true,
		},
	}

	prov.MustComputeTokens(tokens.KnownModules("mws_", mainMod, knownModules, tokens.MakeStandard("mws")))
	prov.SetAutonaming(255, "-")

	return prov
}
